"""The hand-written migration for the Firecrawl adapter tables against the ORM models.

The migration is not autogenerated (autogenerate proposes dropping tables
other services own), so nothing else ties it to the models. This runs its
upgrade on an empty SQLite database and compares every table, column,
nullability, primary key and index with the model, then runs the downgrade.
"""

import importlib.util
from pathlib import Path

import pytest
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import create_engine, inspect

import vdl_tools.shared_tools.database_cache.data_migrations as data_migrations
from vdl_tools.shared_tools.database_cache.database_models.web_scraping import (
    OrgSiteKey,
    ScrapeRun,
    WebPagesHistoryV2,
    WebPagesParsedV2,
    WebPagesScrapedV2,
)

MODELS = (ScrapeRun, WebPagesScrapedV2, WebPagesParsedV2, WebPagesHistoryV2, OrgSiteKey)
MIGRATION = "a41c7e9d2b58_add_scrape_runs_and_v2_page_tables.py"


@pytest.fixture
def migration():
    path = Path(data_migrations.__path__[0]) / "versions" / MIGRATION
    spec = importlib.util.spec_from_file_location("v2_tables_migration", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _run(engine, step):
    with engine.begin() as connection:
        with Operations.context(MigrationContext.configure(connection)):
            step()


def _shape(inspector, table: str) -> dict:
    return {
        "columns": {c["name"]: (c["type"].python_type, c["nullable"]) for c in inspector.get_columns(table)},
        "primary_key": inspector.get_pk_constraint(table)["constrained_columns"],
        "indexes": {i["name"]: (i["column_names"], bool(i["unique"])) for i in inspector.get_indexes(table)},
    }


def test_migration_creates_exactly_what_the_models_declare(migration):
    migrated, declared = create_engine("sqlite://"), create_engine("sqlite://")
    _run(migrated, migration.upgrade)
    for model in MODELS:
        model.__table__.create(declared)

    tables = sorted(m.__tablename__ for m in MODELS)
    assert sorted(inspect(migrated).get_table_names()) == tables
    for table in tables:
        assert _shape(inspect(migrated), table) == _shape(inspect(declared), table), table


def test_downgrade_removes_every_table(migration):
    engine = create_engine("sqlite://")
    _run(engine, migration.upgrade)
    _run(engine, migration.downgrade)
    assert inspect(engine).get_table_names() == []


def test_migration_follows_the_current_head(migration):
    assert migration.down_revision == "36a8b8005ff8"
